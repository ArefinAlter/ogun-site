#!/usr/bin/env python3
"""Reads the OGUN wordmark's pixels out of Departure Mono (SIL OFL 1.1, Helena Zhang) and writes src/art/pixel-wordmark.mjs.

    python -I art/wordmark.py --otf <DepartureMono-Regular.otf>

Departure Mono is drawn on a 50-unit pixel grid: capitals are 5 x 8 pixels with a 7-pixel advance. The glyph outlines are
rectilinear, so the bitmap is exact: every pixel is a square of the font. The site draws it as SVG rectangles, which lets the
wordmark glow, flicker and take a heat gradient per pixel, at any size, with no font download for the large mark.
"""
import argparse
from pathlib import Path

from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
UNIT = 50
TEXT = 'OGUN'


def contours(glyph_set, name):
    pen = RecordingPen()
    glyph_set[name].draw(pen)
    out, cur = [], []
    for op, args in pen.value:
        if op in ('moveTo', 'lineTo'):
            cur.append(args[0])
        elif op in ('closePath', 'endPath'):
            if cur:
                out.append(cur)
            cur = []
        else:
            raise SystemExit(f'curve in {name}: not a pixel glyph')
    return out


def inside(polys, x, y):
    """Even-odd rule over all contours (outer shape and counters)."""
    hit = False
    for poly in polys:
        n = len(poly)
        for i in range(n):
            (x1, y1), (x2, y2) = poly[i], poly[(i + 1) % n]
            if (y1 > y) != (y2 > y) and x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
                hit = not hit
    return hit


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--otf', required=True)
    a = ap.parse_args()
    font = TTFont(a.otf)
    cmap, gs = font.getBestCmap(), font.getGlyphSet()
    cap = font['OS/2'].sCapHeight // UNIT
    rows = [''] * cap
    x_off = 0
    for ch in TEXT:
        name = cmap[ord(ch)]
        adv = gs[name].width // UNIT
        polys = contours(gs, name)
        for r in range(cap):
            y = (cap - 1 - r + 0.5) * UNIT
            rows[r] += ''.join('#' if inside(polys, (c + 0.5) * UNIT, y) else '.' for c in range(adv))
        x_off += adv
    # trim the side bearings so the mark is exactly as wide as its ink
    left = min(r.index('#') for r in rows)
    right = max(r.rindex('#') for r in rows)
    rows = [r[left:right + 1] for r in rows]
    js = '// Generated by art/wordmark.py from Departure Mono (SIL OFL 1.1, copyright 2022-2024 Helena Zhang). Do not edit.\n'
    js += f'export const WORDMARK_TEXT = {TEXT!r}\nexport const WORDMARK_PIXELS = [\n' + ''.join(f"  '{r}',\n" for r in rows) + ']\n'
    (ROOT / 'src' / 'art' / 'pixel-wordmark.mjs').write_text(js)
    print('\n'.join(rows))


if __name__ == '__main__':
    main()
