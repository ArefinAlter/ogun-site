#!/usr/bin/env node
// Writes art/SOURCES.md from art/library.json, public/art/manifest.json and the page mapping in src/art/library.mjs.
//   node tools/sources-md.mjs
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CROPS, PAINTINGS, usesOf } from '../src/art/library.mjs'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const commons = (t) => 'https://commons.wikimedia.org/wiki/' + encodeURI(t.replace(/ /g, '_'))
const rows = Object.entries(PAINTINGS).map(([id, p]) => {
  const crops = Object.entries(CROPS).filter(([k, m]) => m.painting === id && !k.endsWith('-sepia')).map(([k]) => '`' + k + '`')
  return `| \`${id}\` | ${p.artist} (${p.years}), *${p.title}*, ${p.date} | ${p.owner} | [${p.object.label}](${p.object.url}) | ${commons(p.commons)}${p.origin ? ` (${p.origin})` : ''} | ${p.licence} | ${crops.join(', ')} |`
})
const usedRows = Object.keys(PAINTINGS).flatMap((id) => usesOf(id).map(([crop, where]) => `| \`${crop}\` | ${where} |`))
const md = `# Art sources

Every picture on the site is either a public-domain painting translated by \`art/build.py\`, a pixel wordmark read from an open font by \`art/wordmark.py\`, a Studio screenshot of the product's own sample data, or a diagram generated from code in \`src/art/\`. No image comes from an image generator, and no artwork of another website is used. This file is generated by \`node tools/sources-md.mjs\` from \`art/library.json\` (the facts about each painting), \`public/art/manifest.json\` (the crops) and \`src/art/library.mjs\` (where each crop is used); the same data feeds the alt text of every picture and the \`/credits/\` page, the only place where the paintings are credited: they carry no captions on the pages.

Originals are not committed: \`python -I art/build.py --raw <empty scratch dir> --download\` fetches each from Wikimedia Commons (\`Special:FilePath\`, at the width in \`library.json\`), and the script writes only the processed files to \`public/art/\`.

**Licence reasoning.** Every painter died more than 70 years ago (Wright of Derby 1797, Velázquez 1660, Le Nain 1648, Brueghel 1625, Loutherbourg 1812, Turner 1851, Courbet 1877, Monet 1926, Menzel 1905, Meunier 1905, Luce 1941, the latest), so the paintings are in the public domain; Luce's 1897 painting is also public domain in the United States. A faithful photograph of a flat work adds no new right (Commons tags: PD-Art, PD-old). Two photographs carry an open licence of their own as well: Le Nain's *La Forge* by Grégory Lejeune (CC0) and the Cleveland Museum of Art's open-access image of Turner's *Burning of the Houses of Lords and Commons* (CC0). The pixel translations are our adaptation; the originals stay in the public domain.

## Paintings (${Object.keys(PAINTINGS).length})

| Id | Work | Owner and object | Object page | Original file on Wikimedia Commons | Licence tag | Crops |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## Crops and where they are used (${Object.keys(CROPS).filter((k) => !k.endsWith('-sepia')).length}, each in an ember and a sepia grade)

| Crop (file in \`public/art/\`) | Where |
|---|---|
${usedRows.join('\n')}

## Other pictures

| What | Source | Licence |
|---|---|---|
| Pixel wordmark OGUN (\`src/art/pixel-wordmark.mjs\`) | Glyph outlines of Departure Mono 1.500, https://github.com/rektdeckard/departure-mono, copyright 2022 to 2024 Helena Zhang | SIL OFL 1.1 (\`public/fonts/LICENSE-departure-mono.txt\`) |
| Ogun Studio screenshots (\`public/img/studio-*.png\`) | Ogun Studio 0.0.1a on the hosted pre-alpha hub, sample data only, captured with Playwright | Apache-2.0 (the product) |
| Operating-system logos on the download cards | Simple Icons | CC0 |

## Treatment

Treatment parameters are in \`art/build.py\`: the crop (centre and width, with the aspect of the target size), the tone settings per painting (\`TUNE\`: black point, gamma, local contrast; Turner's *Rain, Steam and Speed* and Monet's station are inverted so that the engine becomes the hot iron), the grid (480 x 300 art pixels for the hero, 480 x 96 for the wide bands on pages and between sections, 480 x 140 for the 404 page, 560 x 200 for a panorama behind a call to action, 300 x 170 for the backdrop of a legal page) and the ten-colour ramps (\`RAMPS\`). One art pixel is drawn 2 to 4 CSS pixels wide. The hero is mirrored, so that the glowing iron sits under the Studio slab.
`
writeFileSync(join(ROOT, 'art', 'SOURCES.md'), md)
console.log('art/SOURCES.md', md.length, 'bytes')
